// здесь собраны запросы к таблице растений, чтобы контроллер не работал с базой напрямую.
import { prisma } from '../config/prisma.js'; // подключаем настроенный клиент prisma.

// получаем список растений для каталога и карточек на сайте.
export function listPlants() {
  // обращаемся к модели plants, которая описана в schema.prisma.
  return prisma.plants.findMany({
    // выбираем только поля, которые нужны интерфейсу.
    select: {
      id: true, // уникальный идентификатор растения.
      name: true, // название растения.
      latin_name: true, // научное название, если оно заполнено.
      description: true, // краткое описание растения.
      care_watering_text: true, // текстовая рекомендация по поливу.
      care_lighting_text: true, // текстовая рекомендация по освещению.
      care_temp_text: true, // текстовая рекомендация по температуре.
      water_interval_days: true, // рекомендуемый интервал полива в днях.
      fertilize_interval_days: true, // интервал подкормки в днях.
      spray_interval_days: true, // интервал опрыскивания в днях.
      image_url: true, // ссылка на фотографию растения.
      difficulty_levels: { select: { name: true } }, // подтягиваем название уровня сложности.
      light_types: { select: { name: true } }, // подтягиваем название типа освещения.
      humidity_types: { select: { name: true } }, // подтягиваем описание требований к влажности.
      temp_types: { select: { name: true } }, // подтягиваем температурную категорию.
    },
    // сортируем каталог по названию, чтобы его было легче просматривать.
    orderBy: { name: 'asc' },
    // ограничиваем ответ, чтобы случайно не отправить слишком много записей.
    take: 100,
  });
}
