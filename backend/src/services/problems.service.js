// здесь находятся запросы к справочнику болезней и вредителей.
import { prisma } from '../config/prisma.js'; // используем общий клиент базы данных.

// возвращаем существующие записи справочника без создания тестовых данных.
export function listProblems() {
  return prisma.plant_problems.findMany({
    // выбираем поля, которые нужны странице диагностики.
    select: {
      id: true, // идентификатор записи справочника.
      name: true, // название болезни или вредителя.
      description: true, // описание проблемы.
      treatment: true, // рекомендации по обработке.
      problem_types: { select: { name: true } }, // название категории проблемы.
    },
    // сортируем записи по названию.
    orderBy: { name: 'asc' },
    // ограничиваем размер ответа.
    take: 100,
  });
}
